"""Versioned lexicons and deterministic rule patterns for the baseline engines.

These rules power: silver labels (bootstrap), baseline predictions before
transformer fine-tuning, and the deterministic fallback at inference time.
They are explicitly heuristic and versioned; changes must bump the version in
configs/config.yaml and be recorded in docs/DECISIONS.md.

Sources of patterns: plan sections 12-14 (failure/friction/risk definitions),
17 (aspect taxonomy), 15 (emotion labels), 69 (interpretation rules).
"""

from __future__ import annotations

import re


def compile_any(phrases: list[str], flags: int = re.IGNORECASE) -> re.Pattern:
    """Compile phrase list into one word-boundary regex."""
    parts = [p.strip() for p in phrases if p.strip()]
    return re.compile(r"(?<![A-Za-z])(?:" + "|".join(parts) + r")(?![A-Za-z])", flags)


